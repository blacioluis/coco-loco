import { writeFile } from 'node:fs/promises';

const SOURCE_URL = 'https://www.calabssa.be/c/152_1_forestois_sc/';
const OUTPUT = new URL('../src/app/infrastructure/initial-fixtures.ts', import.meta.url);

const response = await fetch(SOURCE_URL, { headers: { 'user-agent': 'Forestois-SC-calendar-import/1.0' } });
if (!response.ok) throw new Error(`CalABSSA a répondu ${response.status}`);
const html = await response.text();

// CalABSSA publishes its calendar as structured `icalEvents` data in the
// server-rendered Next.js payload. This importer runs at development time only:
// the checked-in generated file remains the site's offline fallback.
const decodedPayload = [...html.matchAll(/self\.__next_f\.push\(\[1,("(?:[^"\\]|\\.)*")\]\)/gs)]
  .map((match) => JSON.parse(match[1]))
  .join('');
const marker = '"icalEvents":';
const start = decodedPayload.indexOf(marker);
if (start < 0) throw new Error('Bloc icalEvents introuvable dans la page CalABSSA');
const events = JSON.parse(readJsonArray(decodedPayload, start + marker.length));
if (!Array.isArray(events) || events.length < 26) throw new Error(`Calendrier incomplet reçu (${events.length} rencontres)`);

const fixtures = events.map(toFixture).sort((a, b) => a.round - b.round);
const updatedAt = new Date().toISOString().slice(0, 10);
const output = `import { Fixture } from '../domain/club.models';\n\n` +
  `// Generated by npm run import:calendar. This checked-in snapshot is the offline fallback.\n` +
  `export const FIXTURES_UPDATED_AT = ${JSON.stringify(updatedAt)};\n\n` +
  `export const INITIAL_FIXTURES: Fixture[] = ${JSON.stringify(fixtures, null, 2)};\n`;
await writeFile(OUTPUT, output, 'utf8');
console.log(`Calendrier CalABSSA importé : ${fixtures.length} rencontres (${updatedAt}).`);

function readJsonArray(value, offset) {
  const begin = value.indexOf('[', offset);
  let depth = 0;
  let quoted = false;
  let escaped = false;
  for (let index = begin; index < value.length; index++) {
    const character = value[index];
    if (quoted) {
      if (escaped) escaped = false;
      else if (character === '\\') escaped = true;
      else if (character === '"') quoted = false;
    } else if (character === '"') quoted = true;
    else if (character === '[') depth++;
    else if (character === ']' && --depth === 0) return value.slice(begin, index + 1);
  }
  throw new Error('Bloc icalEvents tronqué');
}

function toFixture(event) {
  const location = String(event.location ?? '').split(',').map((part) => part.trim());
  const hasVenueName = !/^(rue|avenue|av\.|boulevard|chaussée)/i.test(location[0] ?? '');
  const venue = hasVenueName ? location.shift() : 'Nom du terrain à confirmer';
  const code = /Code terrain:\s*([^\\n]+)/.exec(event.description ?? '')?.[1]?.trim() ?? 'À confirmer';
  const kickoff = toBrusselsDateTime(event.dtstart);
  return {
    round: Number(event.dayNumber),
    date: kickoff.date,
    time: kickoff.time,
    opponent: event.isHome ? event.awayName : event.homeName,
    home: Boolean(event.isHome),
    venue,
    address: location.join(', '),
    venueCode: code,
    status: event.status === 'played' ? 'played' : 'scheduled',
    ...(event.homeScore == null ? {} : { homeScore: Number(event.homeScore) }),
    ...(event.awayScore == null ? {} : { awayScore: Number(event.awayScore) }),
  };
}

function toBrusselsDateTime(value) {
  const parts = new Intl.DateTimeFormat('en-GB', {
    timeZone: 'Europe/Brussels',
    year: 'numeric',
    month: '2-digit',
    day: '2-digit',
    hour: '2-digit',
    minute: '2-digit',
    hourCycle: 'h23',
  }).formatToParts(new Date(value));
  const part = (type) => parts.find((item) => item.type === type)?.value;
  return {
    date: `${part('year')}-${part('month')}-${part('day')}`,
    time: `${part('hour')}:${part('minute')}`,
  };
}
